def _norm(s: str) -> str:
    """归一化：去首尾空白和标点、转小写。`「你好！」`→`你好`，`HI` → `hi`。"""
    return s.strip().strip(_PUNCT).strip().lower()


def kind(text: str) -> str | None:
    """这条消息是哪类寒暄？不是寒暄返回 None。

    **精确匹配，不用 `in`。** 带正文的（「你好我想问下怎么充值」）返回 None，
    照常走问答 —— 这是这个函数最重要的一条性质。

    一个词同时落在两类里的话，先声明的那类赢（`_WORDS` 的字典顺序）。
    **别指望这个顺序**：test_qa.py 有一条专门守「七类之间不许有重复词」，
    真重了就在那里红，而不是靠这里的顺序糊过去。
    """
    s = _norm(text)
    if not s:
        return None
    for k, words in _WORDS.items():
        if s in words:
            return k
    return None


def fallback(k: str, *, straight: bool = False) -> str:
    """固定话术。同一类里随机挑一句，免得每次一模一样。

    `straight=True` = 客户追问第二遍身份，回那句照实说的（见 `_HINT_STRAIGHT`）
    """
    if straight:
        return random.choice(_STRAIGHT_FALLBACK)
    return random.choice(_FALLBACK.get(k) or _FALLBACK[GREET])


def _reject(body: str) -> str:
    """这句能不能发给客户。能发返回空串，不能发返回原因（记日志用）。"""
    s = " ".join(body.split())
    if not s:
        return "空回复"
    if len(s) > _MAX_CHARS:
        return f"太长（{len(s)} 字）"
    if sum(s.count(c) for c in _ENDERS) > _MAX_SENTENCES:
        return "超过两句"
    if any(c.isdigit() for c in s):
        return "出现数字"
    # 数字那道拦得住手机、QQ，拦不住「加 vx：lmuabc」「去 lmuai-free.com」（2026-10-10，见 docs §35）
    bad = foreign_contacts(s)
    if bad:
        return f"出现联系方式 {sorted(bad)}"
    low = s.lower()
    for w in _BANNED:
        if w in low:
            return f"出现禁用词「{w}」"
    return ""


def _missing_name(body: str) -> bool:
    """身份类专有的一道检查：没把名字一字不差说出来就不算合格。

    **为什么不塞进 `_reject()`**：那道检查管的是「有没有开始聊业务」，
    对四类寒暄通用 —— 「你好」的回复不该被要求带名字。

    **为什么非要单独有这一道**：铁律拦不住自称不统一。模型回
    「我是智能助手，有什么可以帮你的」完全过得了 `_reject()`（没数字、
    没禁用词、一句话），但对外招牌就花了。名字是客户拿去认人和搜索的东西，
    今天叫这个明天叫那个，比答错一句话更难收回来。
    """
    return NAME not in body


async def reply(llm: LLM, text: str, k: str, *, straight: bool = False) -> tuple[str, bool]:
    """回一句寒暄。返回（要发的话，是不是模型生成的）。

    `straight=True`：客户**追问第二遍**身份了（同一个群里五分钟内问过第二次，判在 `handlers/qa.py`）。
    第一次只报名、把话头带回正事；他再问就是真想知道，这时候绕下去就是骗人 —— 照实说。

    **不传 max_tokens，用 llm.py 的默认值。** 一句「你好」看着只要几个 token，
    但推理模型会先写一段 reasoning_content，那段同样吃额度且不进 content
    （见 llm.py 的 MAX_TOKENS 注释）。为省钱把它调小，表现是「模型回了空内容」
    而 finish_reason 还写着 stop。额度是上限不是花费，用不到就不收钱。

    **temperature 给 0.7**，和问答那边的 0.2 刻意不同：问答要的是同一个问题
    今天明天答得一样好验收，寒暄要的是别每次都一个字一个字重复。
    """
    if straight:
        k = IDENTITY  # 追问第二遍只可能是身份类，走 identity 那套检查（名字、不许冒充真人）
    try:
        raw = await llm.chat(
            [
                {
                    "role": "system",
                    "content": with_persona(
                        _SYSTEM.format(name=NAME, hint=_HINT_STRAIGHT if straight else _HINT.get(k, ""))
                    ),
                },
                {"role": "user", "content": text},
            ],
            temperature=0.7,
        )
    except LLMError as e:
        log.info("闲聊调模型失败，发固定话术：%s", e)
        return fallback(k, straight=straight), False

    body = " ".join(raw.split()).strip().strip("\"'“”")
    why = _reject(body)
    if why:
        log.info("闲聊回复没过检查（%s），发固定话术：%.40s", why, body)
        return fallback(k, straight=straight), False
    if claims_human(body):
        log.warning("闲聊回复在冒充真人，发固定话术：%.40s", body)
        return fallback(k, straight=straight), False
    if k == IDENTITY and _missing_name(body):
        log.info("闲聊回复没把名字说对，发固定话术：%.40s", body)
        return fallback(k, straight=straight), False
    # 单句末尾的句号去掉：群里真人这么打不带句号（固定话术 fallback 不动）
    return body.removesuffix("。"), True
