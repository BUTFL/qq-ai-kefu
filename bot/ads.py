"""群里有人打别家广告、拉人进群、留联系方式、刷屏：认出来报给超管，开了开关才自动撤回。

2026-09-30 管理员要的：「监督群里有没有打别人家的广告，帮我撤回，比如有没有老板需要0蒸馏，cc，gpt
这类广告语言识别一下要是广告就自动撤回」。他选的：词表初筛 + 模型确认；**先只报不撤，试运行几天**；
除了打广告，顺带管拉人进别的群、留联系方式、刷屏重复发同一条。

---

**为什么不能照他举的例子直接做词表。** 那句话里的「cc」「gpt」正是本店卖的东西，
群里客户天天正常说：「cc 怎么配」「gpt 额度怎么查」「蒸馏版和官方版差在哪」。
拿产品名当广告词，撤掉的是真客户的提问 —— 这比漏掉一条广告难看得多
（`guard.py` 开头记的就是这个教训：客户的正经问题被误伤，客户会截图）。
而且撤回是**删别人的话**，比回一句话重得多，删错了连原文都没了。

**所以这里认的是广告的「结构」，不是产品名。** 一条消息要**同时**命中两组不同的信号才算可疑：

    招揽（有没有老板需要 / 谁要 / 低价出）+ 卖点（蒸馏 / 不限量 / 车队）→ 可疑
    招揽 + 联系方式（加我 / 私我 / vx）                              → 可疑
    拉群（进群 / 群号 / 换群）+ 招揽或联系方式                        → 可疑
    只出现「gpt」「cc」「蒸馏」「加我微信」里的任何一个            → **不算**，一条都不报

单组命中一律放过：广告的特征是「在吆喝」，不是「提到了某个产品」。
他举的那句「有没有老板需要0蒸馏，cc，gpt」命中「有没有老板」（招揽）+「蒸馏」（卖点），两组，收。

**词表只是初筛，最后一道是模型**（`judge`）：把整句话给模型，只回 YES / NO。
模型说不是、模型出错、模型超时 —— 一律当不是，什么都不做。宁可漏，不可误删。

**自己人一律豁免**，不进这道门：同事在群里说「加我微信」「我拉你进群」是正常工作。
名单跟 `listen.py` 同一份（超管 + `.env` 的 TRUSTED + 6099「自己人」页）。

---

**试运行期（`ad_recall` 默认关）**：认定了只私聊超管，群里的消息**不动**。
他看几天觉得准了，`.env` 里 `AD_RECALL=1` 再打开自动撤回。
打开之后也照样私聊 —— 撤回之后群里就看不到那条了，**原文留在私聊里**，
万一撤错了他能立刻发现，也能照着原文把词表调回来。

撤回要机器人是管理员（四个群都是，09-30 查过）。撤不了只记日志：
QQ 对撤别人的消息有时限，超了就撤不动，这不是错误。
"""
from __future__ import annotations

import asyncio
import logging
import re

from .kb.llm import JUDGE_TOKENS, LLM, LLMError

log = logging.getLogger(__name__)

# 认定的类别。进日志和私聊，**不发给群里** —— 撤回本身已经够明显，
# 再补一句「你这是广告」，认错的时候那句最难看（跟 guard.py 的 DECLINE 同一个道理）
AD = "打广告"
PULL = "拉群"
CONTACT = "留联系方式"
SPAM = "刷屏"

# ---- 信号组。**要两组同时命中才算可疑**，单组一律放过（理由见模块开头）----

# 在吆喝：这类话客户问自己的问题时不会说
_SOLICIT = (
    "有没有老板", "有没有人需要", "有没有需要", "需要的老板", "老板们", "有老板",
    "谁要", "谁需要", "有人要吗", "有要的", "要的私", "需要的私", "需要的加",
    "承接", "出售", "低价出", "便宜出", "甩卖", "走量", "接单", "代充", "代下单",
    "供货", "出货", "招代理", "招人", "带你", "教你", "免费领", "免费送", "免费用",
)

# 卖点话术。**单独出现不算** —— 「蒸馏」「不限量」客户问的时候也会说
_CLAIM = (
    "蒸馏", "不限量", "无限量", "无限用", "不掉线", "稳定不掉", "永久", "独享",
    "车队", "拼车", "号池", "逆向", "破解", "白嫖", "白菜价", "内部价", "成本价",
    "一折", "折扣", "特价", "批发价", "秒杀", "原价", "对接官方", "官方直连",
)

# 留联系方式。「微信」「加我」**单独出现不算**：客户跟同事要微信是正常事
_CONTACT_WORDS = (
    "加我", "私我", "私聊我", "滴我", "扣我", "v我", "加微", "微信号", "vx", "wx",
    "二维码", "扫码加", "名片", "详聊", "详谈", "联系我", "找我", "看我主页", "看签名",
)

# 拉人去别的群
_PULL_WORDS = (
    "进群", "加群", "群号", "新群", "换群", "来我群", "我的群", "另一个群",
    "进群领", "进群送", "群里发", "拉你进", "拉个群", "建了个群",
)

# 明摆着是联系方式的写法：连着 5~11 位数字的 QQ 号、微信号那种。
# 单独一串数字不算（订单号、额度、报错码都是数字），要跟「加我」「群」这类词一起才算
_ID_LIKE = re.compile(r"(?:qq|群|微信|vx|wx|v)\s*[:：]?\s*\d{5,11}", re.I)

# 豁免：看着像但在这个群里是正经用法。照 guard.py 的 _EXEMPT，列外不列内
_EXEMPT = (
    # 客户问「你们官方直连吗」是正经问题；这里抠掉的是词本身，不影响别的组命中
    "有没有人用过", "有没有试过", "有没有遇到", "有没有解决",
    # 「进群公告」「进群必读」是我们自己的话
    "进群公告", "进群必读", "进群欢迎",
    # 同事常说的
    "退群", "群公告", "本群", "这个群", "咱们群", "我们群",
)


def _clean(text: str) -> str:
    """归一化：转小写 + 抠掉豁免词。跟 guard.py / crisis.py 同一个写法"""
    s = (text or "").lower()
    for w in _EXEMPT:
        s = s.replace(w, "")
    return s


def suspect(text: str) -> str | None:
    """词表初筛：像广告吗？像就返回类别，不像返回 None。**这只是初筛，还要过 `judge`。**

    返回类别而不是 True：事后翻日志要能看出当时是按哪一类收的
    （「拉群」和「打广告」的可信度不一样）。
    """
    s = _clean(text)
    if not s:
        return None
    solicit = any(w in s for w in _SOLICIT)
    claim = any(w in s for w in _CLAIM)
    contact = any(w in s for w in _CONTACT_WORDS) or bool(_ID_LIKE.search(s))
    pull = any(w in s for w in _PULL_WORDS)
    # 顺序 = 报出来的优先级：打广告最重，其次拉群，最后光留联系方式
    if solicit and (claim or contact):
        return AD
    if pull and (solicit or contact or claim):
        return PULL
    if contact and (claim or pull):
        return CONTACT
    return None


_JUDGE = """你在看一个 AI 模型中转服务的客服群。群里有客户提问，也可能有人来打别家的广告。

判断下面这条消息**是不是在给别家做推广**（招揽生意、卖别家的号或额度、拉人进别的群、留联系方式招客）。

要点：
- 客户**提问、报错、问价格、问怎么用**，都不是广告，哪怕提到 gpt、claude、cc、蒸馏这些词
- 客户**抱怨、催、说别家便宜**，也不是广告 —— 他只是在说事，没在卖东西
- 只有**明显在吆喝、在卖、在拉客**的才算广告

消息：{text}

只回一个词：YES（是广告）或 NO（不是）。"""

# 判断超时。判不出来就当不是，不能卡住
JUDGE_TIMEOUT = 20.0


async def judge(llm: LLM, text: str) -> bool:
    """模型确认这条是不是广告。**出错、超时、答得不像样一律 False**：什么都不做。

    **额度必须用 `JUDGE_TOKENS`，不能图省钱填小**（09-30 另一个会话实测，见 `kb/llm.py` 那段注释）：
    模型回 YES 之前也要先想 90~130 个 token，而 max_tokens 卡的是思考 + 正文的总额，
    填 8 的话 20 次里 18 次正文是空的。**而这里判不出来就当「不是广告」放过去** ——
    所以填小了的表现不是报错，是**盯广告整个看起来在跑、实际上什么都拦不住**，
    日志里只有一行 WARNING。
    """
    try:
        async with asyncio.timeout(JUDGE_TIMEOUT):
            got = await llm.chat(
                [{"role": "user", "content": _JUDGE.format(text=text[:500])}],
                temperature=0, max_tokens=JUDGE_TOKENS,
            )
    except (LLMError, TimeoutError) as e:
        log.warning("判断是不是广告失败，当不是：%s", e)
        return False
    yes = got.strip().upper().startswith("YES")
    log.info("广告？%s：%.60s", "是" if yes else "否", text)
    return yes
