"""不聊的话题：黄、赌、毒、政治。命中就回一句固定话术，AI 全程不参与。

**为什么必须单独一道门，不能靠提示词管住**：2026-09-23 管理员定的红线。
没有这道门的时候，客户在群里说这四类内容，走的是正常问答那一路 ——
查资料查不到 → 记成待办 → 私聊通知超管 → 进日报「等你定调」。
也就是说**红线话题会被系统当成「一个还没写答案的业务问题」催着你去回答**，
这比答错难看得多。

提示词（`kb/smalltalk.py` 的铁律）只能管住**机器人自己说什么**，管不住
**要不要接这个话茬**：客户问「你们老板是不是支持某某」，模型完全可以
一个敏感词都不吐地回一句「这个我不太清楚呢」—— 铁律全过，但机器人已经
在这个话题里了。**接不接**和**怎么说**是两件事，这里管的是前者。

**和退款拦截（`handlers/qa.py` 的 REFUND_WORDS）是同一个套路**：
硬名单、子串匹配、命中即停、不调模型。区别只在退款要转人工、这个不转 ——
红线话题转给人工同事是把麻烦往同事身上推，不是处理。

---

**这里的取词标准：宁可漏，不可误伤。**

跟退款那边「光看一个『退』字会把『退出登录』『退群』全拦掉」是同一条教训，
而且更严重 —— 误伤的后果是**真客户的正经问题被回一句「这个话题我不聊」**，
客户会截图。所以：

- **单字一个都不收。** 「黄」（黄金会员、黄色主题、姓黄）、「色」（颜色、
  角色、特色）、「性」（性能、属性、一次性、稳定性）、「毒」（病毒、杀毒、
  消毒、中毒）、「赌」（打赌、赌一把 —— 这份代码自己的注释里就有「不赌单一
  解析格式」）。这几个字在客服群里几乎全是正经用法。
- **看着像但会误伤的，宁可不收**，都记在下面对应的注释里：
  「六四」（利润六四开）、「彩票」（国内合法，不是要拦的那个东西）、
  「菠菜」（赌博黑话，但也是菜）、「溜冰」（毒品黑话，但也是运动）、
  「主席」（董事会主席）、「白粉」（建材）。
- 实在绕不开的，走 `_EXEMPT` 豁免：「大麻」要收，但「大麻烦」不能中。

**这不是一份完整的敏感词库，也不打算做成完整的。** 它兜的是客服群里
真会出现的那几种搭话。真要按内容安全合规上量，该接第三方接口
（阿里云内容安全 / 腾讯天御），在这里手工堆词表堆不出合规，只会越堆误伤越多。
人名尤其不要往这里加：名单永远不全，而且改名换姓一次就废，那是接口该干的事。
"""
from __future__ import annotations

PORN = "涉黄"
GAMBLE = "涉赌"
DRUG = "涉毒"
POLITICS = "涉政"

# 命中任何一个词就算这个话题。**子串匹配**，跟寒暄白名单的精确匹配刚好相反：
# 寒暄怕的是「你好我想问下怎么充值」被当成打招呼吃掉，所以要精确；
# 这里怕的是「顺便问一句，你们……」夹带一句红线内容被放过，所以要子串。
_WORDS: dict[str, tuple[str, ...]] = {
    # 单字「黄」「色」「性」一个都不能收，理由见模块开头。
    # 「开房」也没收：本身是订酒店的正常说法
    PORN: (
        "色情", "情色", "淫秽", "黄片", "黄网", "黄图", "小黄文", "毛片", "三级片",
        "成人片", "成人网站", "裸聊", "裸照", "约炮", "一夜情", "卖淫", "嫖娼",
        "性交", "性爱", "做爱", "涩图", "porn", "sex",
    ),
    # 「彩票」没收：国内合法发行，跟要拦的不是一回事，收了就是误伤。
    # 「菠菜」没收：是赌博黑话，但也真的是一种菜，闲聊里聊吃的会中
    GAMBLE: (
        "赌博", "赌场", "赌钱", "赌球", "网赌", "博彩", "六合彩", "时时彩", "私彩",
        "百家乐", "老虎机", "下注", "押注", "开盘口", "外围盘",
    ),
    # 「溜冰」「白粉」没收：前者是运动，后者是建材。
    # 「大麻」收了，但「大麻烦」要豁免，见 _EXEMPT
    DRUG: (
        "毒品", "吸毒", "贩毒", "制毒", "冰毒", "海洛因", "可卡因", "鸦片",
        "摇头丸", "大麻", "嗑药",
    ),
    # 「政策」不会被「政治」误伤（不含这两个字连写），但反过来要小心：
    # 别加「政」单字，退款政策、开票政策全中。
    # 「六四」没收：利润六四开。「主席」没收：董事会主席。
    # **人名一律不收**，理由见模块开头最后一段
    POLITICS: (
        "政治", "共产党", "国民党", "中南海", "台独", "港独", "藏独", "疆独",
        "法轮功", "文革", "游行示威", "示威游行", "反华", "颠覆国家",
        "国家领导人", "独裁", "民运",
    ),
}

# 豁免：**先从消息里把这些词抠掉，再去匹配。**
# 「这个太大麻烦了」含「大麻」，是这道门唯一一个绕不开的误伤 ——
# 「大麻」本身太常见不能不收，「大麻烦」在客服群里又是天天说的话。
# 加新词进来之前先想清楚：豁免写宽了就是留后门（"大麻烦" 只挡得住这一种写法，
# 挡不住有人写「大麻 烦」，但那种人本来也不是误伤对象）
_EXEMPT = ("大麻烦",)

# 定版话术。**不指责、不说教、不问为什么**，一句话带回业务。
# 客服群里被回一句重话，客户是会截图的；这句话要经得起截图。
# 也**不解释是哪一类**（「你这是涉政」），认定错了的时候那句解释最难看。
DECLINE = "这个话题我就不聊了，有业务上的问题随时问我。"


def _clean(text: str) -> str:
    """归一化：转小写 + 抠掉豁免词。"""
    s = (text or "").lower()
    for w in _EXEMPT:
        s = s.replace(w, "")
    return s


def topic(text: str) -> str | None:
    """这条消息碰红线了吗？碰了返回类别（`涉黄`/`涉赌`/`涉毒`/`涉政`），没碰返回 None。

    返回的是中文类别，直接进日志 —— 事后翻日志要能一眼看出当时拦的是哪一类，
    光记一个 True 等于没记。**但这个类别不发给客户**，见 `DECLINE` 的注释。
    """
    s = _clean(text)
    if not s:
        return None
    for name, words in _WORDS.items():
        if any(w in s for w in words):
            return name
    return None
