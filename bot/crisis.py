"""有人说想自杀、想伤害自己。命中就回一句关心的话 + 叫人，AI 全程不参与。

2026-09-24 加的。起因是真机日志 09-23 18:59：群里发了一句「我要跳楼了」，
机器人查了向量库（0.361 < 0.49）没查到，回的是**答不上来那套固定话术**：
「这个问题我在资料里没查到，不敢瞎答。已经记下来了，稍后会有人来回复你。」
那条其实是管理员自己的号在自测，不是真客户 —— 但机器人的反应跟客户是谁无关，
下次换成真人，这句话原样再发一遍。

**这是最不该走「查资料 → 待办」那条路的一类话。** 跟红线话题被当成
「一个还没写答案的业务问题」是同一个病（见 guard.py 开头），但后果更重：
资料库里永远不会有这个答案，所以它会**每次都 miss、每次都记待办**，
而客户收到的是一句「稍后会有人回复你」。

---

**这里的取词标准跟 guard.py 刚好相反：宁可误伤，不可漏。**

guard.py 怕的是真客户的正经问题被回一句「这个话题我不聊」，客户会截图，
所以它「单字一个都不收」。这道门怕的是另一件事，代价不对称：
- 误伤的代价 = 有人开个玩笑、收到一句关心的话 + 同事过来看一眼。不体面，但没有伤害；
- 漏掉的代价 = 不用写在这里。

所以话术也是照「万一认错了也说得过去」写的，见 `CARE`。

**但不是没有底线。** 误伤多到一定程度，这道门就废了 —— 不是被谁关掉，
而是超管收多了私聊会开始不看，真出事那条也一起被划过去（警报疲劳）。
所以**在程序员群里有日常用法的词一个都不收**，每条都记在下面的注释里：
- 「一了百了」：重装系统、删库重建，群里天天说；
- 「解脱」：终于配好了 / 终于交付了；
- 「烧炭」：烤肉。只有跟「自杀」连写才算，那种写法词表里已经有了；
- 「安眠药」：真在聊失眠；
- 「撑不住了」「我不行了」：加班、服务器、改不完的 bug。

**「跳楼」收了**，但「跳楼价」「跳楼大甩卖」要豁免 —— 这是个客服群，
促销话术天天说，而且这正是真机上那条原话用的词。

**这不是筛查量表，也不打算做成量表。** 它兜的是一句明说出来的话。
真要做风险识别该请专业的人定规则，在这里堆词表堆不出识别。
"""
from __future__ import annotations

# 全国统一心理援助热线（国家卫健委设的，2025 年 5 月 1 日起全国启用）。
# **只写号码，不写「24 小时」「免费」** —— 这两条 2026-09-24 查了没核实到
# 一手来源。一个说错的承诺（打过去没人接、还要钱）比不说更伤人。
# 号码本身核到了：12356 是卫健委的心理援助热线，12355 是共青团的青少年服务台，
# 别记混。要加「24 小时」先去官网核一遍
HOTLINE = "12356"

# 命中任何一个词就算。**子串匹配**，跟 guard.py 一样：
# 一句「配了一天配不好，不想活了」，要拦的那句是夹在业务话里的
_WORDS: tuple[str, ...] = (
    # 说得最明白的那几种
    "自杀", "自尽", "自缢", "轻生", "寻短见", "想死", "不想活", "活不下去",
    "了结自己", "结束自己", "活着没意思", "活着太累", "活够了", "没法活了",
    # 方式。「跳楼」是真机那条的原话，「跳楼价」走 _EXEMPT 豁免
    "跳楼", "跳河", "跳江", "跳海", "上吊", "割腕", "自残", "自伤",
    "安眠药自杀", "烧炭自杀",
    # 英文。群里有人打英文，而且这几个词在技术语境里几乎不出现
    "suicide", "kill myself", "end my life", "want to die", "self harm",
    "self-harm",
)

# 豁免：**先从消息里把这些词抠掉，再去匹配**（跟 guard._clean 同一个做法）。
# 这里每一条都必须是「在客服群里几乎只有这一个意思」的说法，
# 写宽了就是在这道门上开洞，而这道门开洞的代价见模块开头
_EXEMPT = (
    "跳楼价",  # 促销话术。客服群里的「跳楼」十次有九次是这个
    "跳楼大甩卖",
    "想死你",  # 「想死你了」是熟人打招呼
    "想死我",
)

# 定版话术。**四条硬规矩**，改字之前先看完：
#
# 1. **不诊断、不追问、不说教。** 不写「你是不是抑郁了」「要不要去看看医生」，
#    也不问「怎么了」—— 一个机器人追问细节，人只会关掉窗口。
# 2. **认下「我分不清」。** 群里这句话十次有九次是玩笑（「这 bug 让我想跳楼」），
#    话术要写成「我分不出来，所以宁可当真」。这样万一认错了，看着是笨，不是冒犯；
#    写成「你要想开点」那种，认错了就是难堪。
# 3. **热线号码写进群里那句，不能只放私聊。** 机器人给陌生人发私聊会被
#    「不是好友」挡掉，而这句话是唯一一定送得到的地方。
#    （真出事的时候最不能接受的失败是「他什么都没看到」）
# 4. **不往回拽业务。** guard.DECLINE 末尾那句「有业务上的问题随时问我」
#    在这里是冷的 —— 刚说完这个，马上问人家还有没有别的需求，像没在听。
CARE = (
    "这句话我不敢当成玩笑划过去。要是你只是被气到了，那我多嘴了；"
    "要是真的不太好受，全国心理援助热线是 " + HOTLINE + "，"
    "打过去有人听你说。\n我已经叫同事过来了，别一个人扛着。"
)


def _clean(text: str) -> str:
    """归一化：转小写 + 抠掉豁免词。"""
    s = (text or "").lower()
    for w in _EXEMPT:
        s = s.replace(w, "")
    return s


def hit(text: str) -> str | None:
    """这条消息像不像在说要伤害自己？像就返回**命中的那个词**，不像返回 None。

    返回词本身而不是 True：事后翻日志、或者要判断「这次是不是误伤」，
    得知道当时是哪个词触发的 —— 「跳楼」和「自杀」的可信度差得远。
    **这个词只进日志和私聊，不发给客户**（见 `CARE` 第 1 条）。
    """
    s = _clean(text)
    if not s:
        return None
    for w in _WORDS:
        if w in s:
            return w
    return None
